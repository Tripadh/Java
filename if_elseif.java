public class if_elseif {
    public static void main(String1[] args) {
        char ch = 'A';

        if (ch == 'A' || ch == 'a') {
            System.out.println(ch + " is a vowel.");
        } else if (ch == 'E' || ch == 'e') {
            System.out.println(ch + " is a vowel.");
        } else if (ch == 'I' || ch == 'i') {
            System.out.println(ch + " is a vowel.");
        } else if (ch == 'O' || ch == 'o') {
            System.out.println(ch + " is a vowel.");
        } else if (ch == 'U' || ch == 'u') {
            System.out.println(ch + " is a vowel.");
        } else {
            System.out.println(ch + " is not a vowel.");
        }
    }
}
